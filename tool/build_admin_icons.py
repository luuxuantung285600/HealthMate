"""Bundle pinned admin Lucide icons and current Flutter feature colors.

Usage: python tool/build_admin_icons.py --source-archive <lucide-static.tgz>
No npm dependency or CDN is required by the delivered admin.
"""
import argparse
import hashlib
import json
import re
import tarfile
from pathlib import Path
import xml.etree.ElementTree as ET

parser = argparse.ArgumentParser()
parser.add_argument('--source-archive', type=Path, required=True)
args = parser.parse_args()
source_manifest = json.loads(Path('admin-web/dist/licenses/lucide-source.json').read_text(encoding='utf-8'))
app_icons = source_manifest['icons']
aliases = {
    'overview': 'home', 'revenue': 'premium', 'user_directory': 'profile',
    'food_catalog': 'nutrition', 'workouts': 'workout', 'chatbot': 'chatbot',
    'support': 'support', 'app_config': 'settings2', 'admin_audit': 'history',
    'heart': 'brand', 'logout': 'logOut', 'close': 'x', 'search': 'search',
    'add': 'plus', 'edit': 'squarePen', 'delete': 'trash2', 'download': 'download',
    'refresh': 'refreshCw', 'scanner': 'scanner', 'sun': 'sun', 'moon': 'moon',
    'system': 'smartphone', 'chevron_right': 'chevronRight', 'info': 'info',
    'check': 'check', 'warning': 'triangleAlert',
}
names = {key: app_icons[value]['lucide'] for key, value in aliases.items()}
names.update(menu='panel-left', transactions='receipt-text', buyers='shopping-bag')
nodes, hashes = {}, {}
with tarfile.open(args.source_archive) as archive:
    source_font = archive.extractfile('package/font/lucide.ttf').read()
    assert hashlib.sha256(source_font).hexdigest() == source_manifest['upstream']['sourceFontSha256'], 'Unexpected Lucide archive'
    for alias, name in names.items():
        raw = archive.extractfile(f'package/icons/{name}.svg').read()
        hashes[alias] = hashlib.sha256(raw).hexdigest()
        svg = ET.fromstring(raw)
        nodes[alias] = []
        for element in svg:
            tag = element.tag.rsplit('}', 1)[-1]
            assert tag in {'path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse'}
            assert all(key in {'d', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'x1', 'y1', 'x2', 'y2', 'width', 'height', 'points'} for key in element.attrib)
            nodes[alias].append([tag, element.attrib])
out = Path('admin-web/dist')
(out / 'admin-icons.mjs').write_text(
    '// Generated by tool/build_admin_icons.py; Lucide ' + source_manifest['upstream']['version'] + '.\n'
    '// ISC/MIT notices: licenses/lucide.txt. Independent pinned admin icon source.\n'
    'export const iconNodes = ' + json.dumps(nodes, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
(out / 'licenses').mkdir(exist_ok=True)
license_bytes = (out / 'licenses' / source_manifest['licenseFile']).read_bytes()
assert hashlib.sha256(license_bytes).hexdigest() == source_manifest['licenseSha256'], 'Admin license differs from pinned source'
colors = re.findall(r'(\w+)\(AppIcons\.\w+, 0xFF([A-Fa-f0-9]{6}), 0xFF([A-Fa-f0-9]{6})\)', Path('lib/core/theme/app_feature_visuals.dart').read_text(encoding='utf-8'))
assert len(colors) >= 16, 'Feature colors were not read from Flutter'
css = ['/* Generated from Flutter AppFeatureVisual; do not maintain a second palette. */']
for index, selector in [(1, ':root'), (2, ':root[data-theme="dark"]')]:
    css.append(selector + ' {')
    for color in colors:
        css.append(f'  --feature-{color[0]}: #{color[index].lower()};')
    css.append('}')
for name, _, _ in colors:
    css.append(f'.feature-{name} {{ --feature-color: var(--feature-{name}); }}')
(out / 'feature-identity.css').write_text('\n'.join(css) + '\n', encoding='utf-8')
manifest = {
    'source': source_manifest['upstream'], 'archiveSha256': hashlib.sha256(args.source_archive.read_bytes()).hexdigest(),
    'icons': {alias: {'lucide': name, 'svgSha256': hashes[alias]} for alias, name in names.items()},
    'flutterAliases': aliases, 'colors': {name: {'light': '#' + light.lower(), 'dark': '#' + dark.lower()} for name, light, dark in colors},
}
(out / 'licenses/lucide-manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
print(f'Bundled {len(nodes)} admin icons and {len(colors)} shared feature identities.')
