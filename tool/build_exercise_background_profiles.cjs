// Keep native, app web and admin renderers on the same reviewed coordinates.
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const data=JSON.parse(fs.readFileSync(path.join(root,'data/workouts/exercise-background-regions.json'),'utf8'));
const outputs={
 'lib/features/activity/presentation/exercise_background_profiles.dart':
 `// Generated by tool/build_exercise_background_profiles.cjs.\nconst exerciseBackgroundWidth = ${data.width};\nconst exerciseBackgroundHeight = ${data.height};\nconst exerciseBackgroundProfiles = <String, List<Map<String, Object>>>{\n`+
 Object.entries(data.profiles).map(([id,regions])=>`  '${id}': [\n`+regions.map(r=>`    {'seed': <int>[${r.seed}], 'guards': <List<num>>[${r.guards.map(([x,y,above,threshold])=>`[${x}, ${y}, ${above?1:0}, ${threshold}]`).join(', ')}]},`).join('\n')+'\n  ],').join('\n')+'\n};\n',
 'admin-web/dist/exercise-background-profiles.mjs':
 `// Generated by tool/build_exercise_background_profiles.cjs.\nexport const exerciseBackgroundProfiles=${JSON.stringify(data.profiles)};\n`,
 'admin-web/dist/exercise-background-profiles.css':
 '/* Generated by tool/build_exercise_background_profiles.cjs; external for CSP. */\n'+
 Object.keys(data.profiles).map(id=>`:root[data-theme="dark"] .exercise-media-frame img[src^="https://static.exercisedb.dev/media/${id}.gif"],:root[data-theme="dark"] .exercise-detail-image[src^="https://static.exercisedb.dev/media/${id}.gif"],:root[data-theme="dark"] .exercise-source-thumb-image[data-source-id="${id}"]{filter:url(#healthmate-admin-exercise-background-v4-${id})}`).join('\n')+'\n',
};
for(const [file,content] of Object.entries(outputs)) {
 const target=path.join(root,file);
 if(process.argv.includes('--check')) {
  // Dart formatting is intentional; compare whitespace-insensitive tokens.
  const normalize=s=>s.replace(/\s/g,'').replace(/,([\]}])/g,'$1');
  if(!fs.existsSync(target)||normalize(fs.readFileSync(target,'utf8'))!==normalize(content))throw Error(`Stale ${file}`);
 } else fs.writeFileSync(target,content);
}
