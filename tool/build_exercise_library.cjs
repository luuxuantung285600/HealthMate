// Editorial input contains stable provider IDs, never provider responses or media.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const entries = JSON.parse(fs.readFileSync(path.join(root, 'data/workouts/exercise-library.json'), 'utf8'));
const regions = new Set(['chest', 'back', 'legs', 'shoulders', 'arms', 'core', 'cardio']);
const equipment = new Set(['bodyweight', 'dumbbell', 'barbell', 'cable', 'machine', 'band', 'kettlebell']);
if (entries.length < 50) throw Error('The library must retain at least 50 exercises');
const ids = new Set();
for (const e of entries) {
  if (!/^[A-Za-z0-9]{7}$/.test(e.sourceId) || e.id !== `edb-${e.sourceId}` || ids.has(e.id)) throw Error(`Invalid ID: ${e.id}`);
  ids.add(e.id);
  if (!regions.has(e.region) || !equipment.has(e.equipment) || e.isActive !== true) throw Error(`Invalid classification: ${e.id}`);
  if (![e.name, e.target, e.easier].every(v => typeof v === 'string' && v.trim()) || !Array.isArray(e.steps) || e.steps.length < 2 || e.steps.length > 6 || !e.steps.every(v => typeof v === 'string' && v.trim())) throw Error(`Invalid guidance: ${e.id}`);
  if (e.name.length > 120 || e.target.length > 160 || e.easier.length > 400 || e.steps.some(v => v.length > 400)) throw Error(`Guidance too long: ${e.id}`);
  if (Object.keys(e).sort().join(',') !== ['id','sourceId','name','region','equipment','target','steps','easier','isActive'].sort().join(',')) throw Error(`Unexpected fields: ${e.id}`);
  if (/https?:|gifUrl|instructions/i.test(JSON.stringify(e))) throw Error(`Provider content must not be bundled: ${e.id}`);
}
const quote = s => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$') + "'";
const dart = "// Generated by tool/build_exercise_library.cjs. Edit the editorial JSON.\nimport '../models/exercise_library_entry.dart';\n\nconst bundledExerciseLibrary = <ExerciseLibraryEntry>[\n" + entries.map(e => '  ExerciseLibraryEntry(\n' + Object.entries(e).map(([k,v]) => `    ${k}: ${Array.isArray(v) ? '[' + v.map(quote).join(', ') + ']' : typeof v === 'string' ? quote(v) : v},`).join('\n') + '\n  ),').join('\n') + '\n];\n';
const js = '// Generated by tool/build_exercise_library.cjs. Edit the editorial JSON.\nexport const bundledExerciseLibrary = ' + JSON.stringify(entries, null, 2) + ';\n';
const outputs = [['lib/features/activity/data/bundled_exercise_library.dart', dart], ['admin-web/dist/bundled-exercise-library.mjs', js]];
for (const [file, content] of outputs) {
  const target = path.join(root, file);
  if (process.argv.includes('--check')) {
    const actual = fs.readFileSync(target, 'utf8');
    // dart format changes whitespace and can add a trailing comma in lists.
    const normalize = text => text.replace(/\s/g, '').replace(/,\]/g, ']');
    if (file.endsWith('.mjs') ? actual !== content : normalize(actual) !== normalize(content)) throw Error(`${file} is stale`);
  } else { fs.mkdirSync(path.dirname(target), {recursive:true}); fs.writeFileSync(target, content); }
}
console.log(`Validated ${entries.length} unique exercises; ${process.argv.includes('--check') ? 'checked' : 'generated'} Dart and web catalogs.`);
