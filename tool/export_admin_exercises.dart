import 'dart:convert';
import 'dart:io';

import 'package:healthmate/features/activity/models/exercise_catalog.dart';

// Export the app's actual catalog. The admin must not maintain a second copy.
void main(List<String> args) {
  final data = {
    'sourcePath': 'lib/features/activity/models/exercise_catalog.dart',
    'sourceUrl':
        'https://sites.google.com/site/compendiumofphysicalactivities/',
    'categories': {
      for (final category in ExerciseCategory.values)
        category.name: category.label,
    },
    'items': [
      for (final item in ExerciseCatalog.exercises)
        {
          'id': item.id,
          'name': item.name,
          'category': item.category.name,
          'met': item.met,
          'description': item.description,
        },
    ],
  };
  final content =
      '// Generated by tool/export_admin_exercises.dart; do not edit.\n'
      'export const exerciseCatalog = ${const JsonEncoder.withIndent('  ').convert(data)};\n';
  final file = File('admin-web/dist/exercise-catalog.mjs');
  if (args.contains('--check')) {
    if (!file.existsSync() || file.readAsStringSync() != content) {
      stderr.writeln('Admin exercise catalog differs from the app. Re-export.');
      exitCode = 1;
      return;
    }
    stdout.writeln(
      'Admin catalog matches ${ExerciseCatalog.exercises.length} app exercises.',
    );
    return;
  }
  file.writeAsStringSync(content);
  stdout.writeln('Exported ${ExerciseCatalog.exercises.length} app exercises.');
}
