// Generate only classification metadata; food nutrition and identity stay unchanged.
const fs = require('node:fs');
const source = fs.readFileSync('lib/features/nutrition/models/food_browse_group.dart', 'utf8');
const sets = {};
for (const [, name, body] of source.matchAll(/const _(\w+) = \{([\s\S]*?)\};/g)) {
  sets[name] = [...body.matchAll(/'([^']*)'/g)].map(match => match[1]);
}
const groups = [...source.matchAll(/^  (\w+)\('([^']+)'\)[,;]/gm)]
  .map(([, id, label]) => ({id, label}));
if (groups.length !== 10 || !sets.meatHeads || !sets.seafoodHeads) throw Error('Flutter browse metadata changed; review generator.');
const reviewed = JSON.parse(fs.readFileSync('data/food_catalog/fruit-drink-browse.json', 'utf8'));
const index = Object.fromEntries(Object.entries(reviewed.groups).flatMap(([group, rows]) => rows.map((row, order) => [row.id, {group, order}])));
fs.writeFileSync('admin-web/dist/food-browse-metadata.mjs',
  '// Generated by tool/build_admin_food_browse_groups.cjs from Flutter browse definitions.\n' +
  `export const foodBrowseGroups = ${JSON.stringify(groups, null, 2)};\n` +
  `export const browseSets = ${JSON.stringify(sets, null, 2)};\n` +
  `export const foodBrowseIndex = ${JSON.stringify(index, null, 2)};\n`);
console.log(`Generated ${groups.length} groups and ${Object.keys(index).length} reviewed identities.`);
