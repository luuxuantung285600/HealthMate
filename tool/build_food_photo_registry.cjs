// Offline only. manifest.json is the reviewed source of truth for photo credits.
const fs = require('node:fs');
const {createHash} = require('node:crypto');
const {photos} = JSON.parse(fs.readFileSync('assets/food_photos/manifest.json', 'utf8'));
const release = JSON.parse(fs.readFileSync('data/food_catalog/photo-release.json', 'utf8'));
const scope = new Set(release.scopeIds);
const visible = new Set(release.visibleIds);
if (scope.size !== release.scopeIds.length || visible.size !== release.visibleIds.length ||
    [...visible].some(id => !scope.has(id))) throw Error('Invalid photo release scope');
const excluded = release.excluded.map(row => row.id).sort();
if (new Set(excluded).size !== excluded.length ||
    excluded.some(id => !scope.has(id) || visible.has(id)) ||
    excluded.length + visible.size !== scope.size) throw Error('Invalid photo release partition');
const excludedSet = new Set(excluded);
const fdcIds = new Set();
for (const path of ['assets/nutrition/vietnamese-foods.json', 'assets/nutrition/usda-sr-legacy.json', 'assets/nutrition/usda-current.json']) {
  for (const food of JSON.parse(fs.readFileSync(path, 'utf8')).foods) {
    if (excludedSet.has(food.id) && Number.isInteger(food.fdcId)) fdcIds.add(food.fdcId);
  }
}
fs.writeFileSync('lib/features/nutrition/data/bundled_food_photo_visibility.dart',
  `// Generated by tool/build_food_photo_registry.cjs from photo-release.json.\n` +
  `// Public catalog exclusions apply offline; historical snapshots remain intact.\n` +
  `const excludedFoodPhotoIds = <String>{\n${excluded.map(id => `  ${JSON.stringify(id)},`).join('\n')}\n};\n\n` +
  `const excludedFoodPhotoFdcIds = <int>{\n${[...fdcIds].sort((a,b) => a-b).map(id => `  ${id},`).join('\n')}\n};\n`);
const quote = value => JSON.stringify(value).replace(/\$/g, '\\$');
const fields = ['foodId','foodName','assetPath','title','author','sourceUrl','license','licenseUrl'];
const entries = photos.map(photo => {
  const hash = createHash('sha256').update(fs.readFileSync(photo.assetPath)).digest('hex');
  if (hash !== photo.sha256) throw Error(`Photo differs from reviewed manifest: ${photo.foodId}`);
  return `  ${quote(photo.foodId)}: FoodPhoto(\n${fields.map(key => `    ${key}: ${quote(photo[key])},`).join('\n')}\n  ),`;
});
fs.writeFileSync('lib/features/nutrition/data/bundled_food_photos.dart', `// Generated by tool/build_food_photo_registry.cjs from reviewed local media.
import '../models/food_photo.dart';
import '../models/food_catalog_search.dart';

const bundledFoodPhotos = <String, FoodPhoto>{
${entries.join('\n')}
};

/// IDs alone cannot attach an old photo to a renamed catalog entry.
FoodPhoto? findFoodPhoto(String foodId, String foodName) {
  final photo = bundledFoodPhotos[foodId];
  if (photo == null ||
      normalizeFoodSearch(photo.foodName) != normalizeFoodSearch(foodName)) {
    return null;
  }
  return photo;
}
`);
fs.writeFileSync('assets/food_photos/ATTRIBUTION.md', `# Food photo attribution\n\nLocal illustrative food media, reviewed 2026-11-10. Each derivative retains its original license; image licenses do not apply to app code. No nutrition is inferred from photos.\n\n${photos.map(p => `## ${p.foodName}\n\n- File: ${p.assetPath}\n- Original: [${p.title}](${p.sourceUrl})\n- Author: ${p.author}\n- License: [${p.license}](${p.licenseUrl})\n- Changes: ${p.changes}\n- SHA-256: ${p.sha256}\n`).join('\n').trimEnd()}\n`);
console.log(`Generated registry and attribution for ${photos.length} verified files.`);
